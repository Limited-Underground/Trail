package io.github.nbjelanovic.otclient

import java.util.Collections

/** Unsigned values preserve the host inbox's exact scope/key widths. Not a wire format. */
data class V1InboxKey(val context: ULong, val recipient: ULong, val epoch: UInt,
                      val source: ULong, val message: UInt) {
    internal fun valid() = context != 0uL && recipient != 0uL && epoch != 0u && source != 0uL && message != 0u
    override fun toString() = "V1InboxKey(redacted)"
}

class V1InboxDeviceToken private constructor(private val bytes: ByteArray) {
    override fun equals(other: Any?) = other is V1InboxDeviceToken && bytes.contentEquals(other.bytes)
    override fun hashCode() = bytes.contentHashCode()
    override fun toString() = "V1InboxDeviceToken(redacted)"
    internal fun copyBytes(): ByteArray = bytes.copyOf()
    companion object {
        fun create(bytes: ByteArray): V1InboxDeviceToken? = bytes.takeIf {
            it.size == 16 && it.any { byte -> byte != 0.toByte() }
        }?.copyOf()?.let(::V1InboxDeviceToken)
    }
}

enum class V1InboxFullPolicy { UNSPECIFIED, REJECT_NEW }
/** retentionMs is local phone-history retention, NOT device/radio TTL or a wire timeout. */
data class V1InboxPolicy(val records: Int, val utf8Bytes: Int, val retentionMs: Long,
                         val full: V1InboxFullPolicy) {
    internal fun valid() = records > 0 && utf8Bytes > 0 && retentionMs > 0 && full == V1InboxFullPolicy.REJECT_NEW
}

/**
 * Authentication is a trusted caller precondition. A future adapter must verify
 * the current paired-device/session and scope plus group membership or accepted
 * direct consent. A source alias is NOT a V1DirectPeerToken: mapping to peer must
 * be explicitly authenticated. This object is not proof generated by the model.
 * Reconstruct access from current authority for each call; never cache an old
 * accepted contact or reuse access after membership/consent/session revocation.
 */
sealed class V1InboxAccess protected constructor(
    internal val device: V1InboxDeviceToken,
    internal val key: V1InboxKey,
) {
    class Group internal constructor(device: V1InboxDeviceToken, key: V1InboxKey) : V1InboxAccess(device, key)
    class Direct internal constructor(device: V1InboxDeviceToken, key: V1InboxKey,
                                      internal val contact: V1DirectContact) : V1InboxAccess(device, key)
    final override fun toString() = "V1InboxAccess(redacted)"
}

enum class V1InboxReceiptKind { IMPORTED, READ }
data class V1InboxReceiptId(val device: V1InboxDeviceToken, val key: V1InboxKey,
                           val kind: V1InboxReceiptKind) {
    override fun toString() = "V1InboxReceiptId(kind=$kind, identity=redacted)"
}

/** No receipt transmission, remote delivery or read confirmation is implied. */
class V1InboxMessage internal constructor(
    val key: V1InboxKey,
    val text: String,
    val directPeer: V1DirectPeerToken?,
    val opened: Boolean,
) {
    val locationSharingEnabled: Boolean get() = false
    override fun toString() = "V1InboxMessage(opened=$opened, content=redacted)"
}

class V1InboxStoredRecord internal constructor(
    internal val key: V1InboxKey,
    internal val text: String,
    internal val directPeer: V1DirectPeerToken?,
    internal val remainingMs: Long,
    internal val opened: Boolean = false,
    internal val importPending: Boolean = true,
    internal val readPending: Boolean = false,
) {
    internal fun changed(remainingMs: Long = this.remainingMs, opened: Boolean = this.opened,
                         importPending: Boolean = this.importPending, readPending: Boolean = this.readPending) =
        V1InboxStoredRecord(key, text, directPeer, remainingMs, opened, importPending, readPending)
    override fun toString() = "V1InboxStoredRecord(redacted)"
}

/** Typed immutable storage contract only; no persistent byte schema or Android adapter. */
class V1InboxSnapshot internal constructor(
    internal val device: V1InboxDeviceToken,
    internal val policy: V1InboxPolicy,
    records: List<V1InboxStoredRecord>,
    internal val generation: ULong,
    internal val version: Int = 1,
) {
    internal val records: List<V1InboxStoredRecord> = Collections.unmodifiableList(ArrayList(records))
    override fun toString() = "V1InboxSnapshot(records=${records.size}, content=redacted)"
}

sealed interface V1InboxLoad {
    data object Empty : V1InboxLoad
    class Found(val snapshot: V1InboxSnapshot) : V1InboxLoad {
        override fun toString() = "V1InboxLoad.Found(redacted)"
    }
    data object Failed : V1InboxLoad
}
enum class V1InboxCommit { VERIFIED, FAILED_BEFORE_COMMIT, UNCERTAIN }
interface V1InboxStorage {
    fun read(): V1InboxLoad
    /** VERIFIED requires atomic recoverable commit and exact readback verification. */
    fun commit(snapshot: V1InboxSnapshot): V1InboxCommit
}

enum class V1InboxFailure { NONE, INVALID, UNAVAILABLE, UNAUTHORIZED, CONFLICT, FULL,
    STORAGE_FAILURE, RECOVERY_REQUIRED, CORRUPT, TIME_UNCERTAIN, CLOCK_FAULT, MISSING, EXPIRED, IMPORT_PENDING }
class V1InboxReceiptsResult internal constructor(
    val failure: V1InboxFailure,
    receipts: List<V1InboxReceiptId> = emptyList(),
) {
    val receipts: List<V1InboxReceiptId> = Collections.unmodifiableList(ArrayList(receipts))
    override fun toString() = "V1InboxReceiptsResult(failure=$failure, count=${receipts.size}, identity=redacted)"
}
class V1InboxResult internal constructor(
    val failure: V1InboxFailure,
    val message: V1InboxMessage? = null,
    val receipt: V1InboxReceiptId? = null,
    val duplicate: Boolean = false,
) {
    override fun toString() = "V1InboxResult(failure=$failure, content=redacted)"
}

/** Host-only, serialized owner. Backend reentry fails closed; no BLE or receipt transport. */
class V1SynchronizedInbox(
    private val device: V1InboxDeviceToken,
    private val policy: V1InboxPolicy,
    private val storage: V1InboxStorage,
) {
    private var live: V1InboxSnapshot? = null
    private var savedAt = 0L
    private var lastNow = 0L
    private var busy = false
    private var fault = false

    @Synchronized fun restore(nowMs: Long, elapsedSinceCheckpointMs: Long?): V1InboxFailure {
        if (busy || live != null || fault || !policy.valid() || nowMs < 0) return V1InboxFailure.INVALID
        busy = true
        val loaded = try { storage.read() } catch (_: Exception) { V1InboxLoad.Failed } finally { busy = false }
        val snapshot = when (loaded) {
            V1InboxLoad.Empty -> V1InboxSnapshot(device, policy, emptyList(), 0uL)
            V1InboxLoad.Failed -> return V1InboxFailure.STORAGE_FAILURE
            is V1InboxLoad.Found -> {
                val source = loaded.snapshot
                if (!valid(source)) { fault = true; return V1InboxFailure.CORRUPT }
                // Includes ALL time since the stored snapshot, not just powered-off time.
                if (elapsedSinceCheckpointMs == null) return V1InboxFailure.TIME_UNCERTAIN
                if (elapsedSinceCheckpointMs < 0) return V1InboxFailure.INVALID
                aged(source, elapsedSinceCheckpointMs)
            }
        }
        return save(snapshot, nowMs)
    }

    @Synchronized fun importMessage(access: V1InboxAccess, text: String,
                                    directPeer: V1DirectPeerToken?, nowMs: Long): V1InboxResult {
        if (!authorized(access, access.key, directPeer)) return result(V1InboxFailure.UNAUTHORIZED)
        if (!validText(text)) return result(V1InboxFailure.INVALID)
        val (failure, current) = prepare(nowMs)
        if (failure != V1InboxFailure.NONE) return result(failure)
        val snapshot = requireNotNull(current)
        val existing = snapshot.records.find { it.key == access.key }
        if (existing != null && (existing.text != text || existing.directPeer != directPeer)) return result(V1InboxFailure.CONFLICT)
        if (existing?.remainingMs == 0L) return result(V1InboxFailure.EXPIRED)
        val record = existing?.changed(importPending = true) ?: V1InboxStoredRecord(access.key, text, directPeer, policy.retentionMs)
        if (existing == null && (snapshot.records.size >= policy.records ||
            snapshot.records.sumOf { utf8Size(it.text).toLong() } + utf8Size(text) > policy.utf8Bytes)) return result(V1InboxFailure.FULL)
        val records = if (existing == null) snapshot.records + record else snapshot.records.map { if (it.key == record.key) record else it }
        val saved = save(copy(snapshot, records), nowMs)
        return if (saved != V1InboxFailure.NONE) result(saved) else V1InboxResult(
            V1InboxFailure.NONE, visible(record), receipt(record, V1InboxReceiptKind.IMPORTED), existing != null)
    }

    @Synchronized fun present(access: V1InboxAccess, nowMs: Long): V1InboxResult {
        val (failure, snapshot) = prepare(nowMs)
        if (failure != V1InboxFailure.NONE) return result(failure)
        val record = snapshot!!.records.find { it.key == access.key } ?: return result(V1InboxFailure.MISSING)
        if (!authorized(access, record.key, record.directPeer)) return result(V1InboxFailure.UNAUTHORIZED)
        if (record.remainingMs == 0L) return result(V1InboxFailure.EXPIRED)
        return V1InboxResult(V1InboxFailure.NONE, visible(record))
    }

    /** Invoke only for an explicit opened-message event, never list/import/reconnect. */
    @Synchronized fun opened(access: V1InboxAccess, nowMs: Long): V1InboxResult {
        val (failure, snapshot) = prepare(nowMs)
        if (failure != V1InboxFailure.NONE) return result(failure)
        val record = snapshot!!.records.find { it.key == access.key } ?: return result(V1InboxFailure.MISSING)
        if (!authorized(access, record.key, record.directPeer)) return result(V1InboxFailure.UNAUTHORIZED)
        if (record.remainingMs == 0L) return result(V1InboxFailure.EXPIRED)
        val next = record.changed(opened = true, readPending = true)
        val saved = save(copy(snapshot, snapshot.records.map { if (it.key == record.key) next else it }), nowMs)
        return if (saved != V1InboxFailure.NONE) result(saved) else
            V1InboxResult(V1InboxFailure.NONE, visible(next), receipt(next, V1InboxReceiptKind.READ))
    }

    @Synchronized fun pendingReceipts(access: V1InboxAccess, nowMs: Long): V1InboxReceiptsResult {
        val (failure, snapshot) = prepare(nowMs)
        if (failure != V1InboxFailure.NONE) return V1InboxReceiptsResult(failure)
        val record = snapshot!!.records.find { it.key == access.key }
            ?: return V1InboxReceiptsResult(V1InboxFailure.MISSING)
        if (!authorized(access, record.key, record.directPeer)) return V1InboxReceiptsResult(V1InboxFailure.UNAUTHORIZED)
        return V1InboxReceiptsResult(V1InboxFailure.NONE, buildList {
            if (record.importPending) add(receipt(record, V1InboxReceiptKind.IMPORTED))
            if (record.readPending) add(receipt(record, V1InboxReceiptKind.READ))
        })
    }

    /** Caller supplies exact authenticated handoff confirmation, not a local send attempt. */
    @Synchronized fun confirmHandoff(access: V1InboxAccess, receipt: V1InboxReceiptId, nowMs: Long): V1InboxFailure {
        if (receipt.device != device || receipt.key != access.key) return V1InboxFailure.INVALID
        val (failure, snapshot) = prepare(nowMs)
        if (failure != V1InboxFailure.NONE) return failure
        val record = snapshot!!.records.find { it.key == receipt.key } ?: return V1InboxFailure.MISSING
        if (!authorized(access, record.key, record.directPeer)) return V1InboxFailure.UNAUTHORIZED
        // A Read handoff must not precede confirmation of durable phone import.
        if (receipt.kind == V1InboxReceiptKind.READ && record.importPending) return V1InboxFailure.IMPORT_PENDING
        if ((receipt.kind == V1InboxReceiptKind.IMPORTED && !record.importPending) ||
            (receipt.kind == V1InboxReceiptKind.READ && !record.readPending)) return V1InboxFailure.MISSING
        val next = when (receipt.kind) {
            V1InboxReceiptKind.IMPORTED -> record.changed(importPending = false)
            V1InboxReceiptKind.READ -> record.changed(readPending = false)
        }
        return save(copy(snapshot, snapshot.records.map { if (it.key == record.key) next else it }), nowMs)
    }

    private fun authorized(access: V1InboxAccess, key: V1InboxKey, peer: V1DirectPeerToken?): Boolean =
        access.device == device && access.key == key && key.valid() && if (peer == null) {
            access is V1InboxAccess.Group
        } else {
            access is V1InboxAccess.Direct && access.contact.peerToken == peer && access.contact.state == V1DirectContactState.ACCEPTED
        }

    private fun prepare(nowMs: Long): Pair<V1InboxFailure, V1InboxSnapshot?> {
        if (busy) return V1InboxFailure.UNAVAILABLE to null
        if (fault) return V1InboxFailure.RECOVERY_REQUIRED to null
        val snapshot = live ?: return V1InboxFailure.UNAVAILABLE to null
        if (nowMs < 0 || nowMs < lastNow) { fault = true; return V1InboxFailure.CLOCK_FAULT to null }
        lastNow = nowMs
        return V1InboxFailure.NONE to aged(snapshot, nowMs - savedAt)
    }

    private fun save(snapshot: V1InboxSnapshot, nowMs: Long): V1InboxFailure {
        if (snapshot.generation == ULong.MAX_VALUE) { fault = true; return V1InboxFailure.RECOVERY_REQUIRED }
        val retained = snapshot.records.filter { it.remainingMs > 0 || it.importPending || it.readPending }
        val next = V1InboxSnapshot(device, policy, retained, snapshot.generation + 1uL)
        busy = true
        val outcome = try { storage.commit(next) } catch (_: Exception) { V1InboxCommit.UNCERTAIN } finally { busy = false }
        return when (outcome) {
            V1InboxCommit.VERIFIED -> { live = next; savedAt = nowMs; lastNow = nowMs; V1InboxFailure.NONE }
            V1InboxCommit.FAILED_BEFORE_COMMIT -> V1InboxFailure.STORAGE_FAILURE
            V1InboxCommit.UNCERTAIN -> { fault = true; V1InboxFailure.RECOVERY_REQUIRED }
        }
    }

    private fun valid(snapshot: V1InboxSnapshot): Boolean = snapshot.version == 1 &&
        snapshot.device == device && snapshot.policy == policy && snapshot.generation != 0uL &&
        snapshot.records.size <= policy.records && snapshot.records.map { it.key }.distinct().size == snapshot.records.size &&
        snapshot.records.sumOf { utf8Size(it.text).toLong() } <= policy.utf8Bytes &&
        snapshot.records.all { it.key.valid() && validText(it.text) && it.remainingMs in 0..policy.retentionMs &&
            (it.remainingMs > 0 || it.importPending || it.readPending) && (!it.readPending || it.opened) }

    private fun aged(snapshot: V1InboxSnapshot, elapsed: Long) = copy(snapshot,
        snapshot.records.mapNotNull {
            val remaining = (it.remainingMs - elapsed).coerceAtLeast(0)
            if (remaining > 0 || it.importPending || it.readPending) it.changed(remainingMs = remaining) else null
        })
    private fun copy(snapshot: V1InboxSnapshot, records: List<V1InboxStoredRecord>) =
        V1InboxSnapshot(device, policy, records, snapshot.generation)
    private fun utf8Size(text: String) = text.toByteArray(Charsets.UTF_8).size
    private fun validText(text: String) = text.isNotBlank() && text.length <= policy.utf8Bytes &&
        text.none { it.isISOControl() && it != '\n' } && Charsets.UTF_8.newEncoder().canEncode(text) && utf8Size(text) <= policy.utf8Bytes
    private fun visible(record: V1InboxStoredRecord) = V1InboxMessage(record.key, record.text, record.directPeer, record.opened)
    private fun receipt(record: V1InboxStoredRecord, kind: V1InboxReceiptKind) = V1InboxReceiptId(device, record.key, kind)
    private fun result(failure: V1InboxFailure) = V1InboxResult(failure)
}
